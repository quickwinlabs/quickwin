#define DEC(ts, c) printf("    %s = %d, // 0x%X\n", #ts, (int)(c), (unsigned)(c));
/* 失败哨兵用的两个宏：和 DEC 的唯一差别是值的转换符，而这正是全部意义 ——
   绑定里 `-> u32` 无符号读回、`-> <>ptr`/`<X>ptr` 有符号读回（-1 保真），
   所以同一个全 1 位模式在两族的比较值不同：
     u32 族 → DEC_U32C：印 4294967295
     ptr 族 → DEC_PTRC：印 -1
   混用任一方（例如 ptr 族走 %u）会写出和返回值永远不相等的常量。 */
#define DEC_U32C(ts, c) printf("    %s = %u, // 0x%X\n", #ts, (unsigned)(c), (unsigned)(c));
#define DEC_PTRC(ts, c) printf("    %s = %d,\n", #ts, (int)(LONG_PTR)(c));
#define DEC_GUID(name, guid) do { \
    GUID _g = (guid); \
    printf("    %s = '{%08lX-%04hX-%04hX-%02X%02X-%02X%02X%02X%02X%02X%02X}',\n", \
        name, _g.Data1, _g.Data2, _g.Data3, \
        _g.Data4[0], _g.Data4[1], _g.Data4[2], _g.Data4[3], \
        _g.Data4[4], _g.Data4[5], _g.Data4[6], _g.Data4[7]); \
} while(0)

/* ── EnumMap 预填段的生成器 ────────────────────────────────────────────────
   constants.ts 末尾的 `declare global { interface EnumMap {…} }`（token 标注
   'u32@Name' / '<>ptr@Name' 的值域表，消费点在 lib/ffi/ctype.ts）由这里生成：
   ENUM() 打印每个 const enum 时记下名字，全部打完后 print_enum_map() 按记录顺序
   吐接口成员，并按 *Msg 后缀聚合出 AnyMsg。整段与 enum 定义同批输出、同批提交 ——
   既不会漂移，也不再需要后处理脚本。constants.ts 是 module，所以预填必须包在
   declare global 里才对全局生效（由 quickwin.d.ts 顶部的 /// <reference> 带进程序）。 */
#define ENUM_MAP_INIT 256

static const char **g_enum_names = NULL;
static int g_enum_count = 0;
static int g_enum_cap = 0;

/* 登记枚举名。数量随 gen_const.c 里的 enum 增长，按需扩容 —— 不设上限，
   也就没有"超限静默截断"这种最坏情况（预填悄悄缺项）。只会在 OOM 时失败。 */
static void enum_map_record(const char *name)
{
    if (g_enum_count == g_enum_cap) {
        int cap = g_enum_cap ? g_enum_cap * 2 : ENUM_MAP_INIT;
        const char **p = realloc(g_enum_names, (size_t)cap * sizeof(*p));
        if (!p) {
            fprintf(stderr, "gen_const: out of memory recording enum names\n");
            exit(1);
        }
        g_enum_names = p;
        g_enum_cap = cap;
    }
    g_enum_names[g_enum_count++] = name;
}

#define ENUM(name) do { \
    printf("export const enum %s {\n", #name); \
    enum_map_record(#name); \
} while(0)

static int has_msg_suffix(const char *name)
{
    size_t n = strlen(name);
    return n >= 3 && strcmp(name + n - 3, "Msg") == 0;
}

static void print_enum_map(void)
{
    int i, first = 1;

    printf("// ── EnumMap 预填 —— 由 tools/gen_const.c 生成，勿手改（改 enum 定义后重跑 make gen-const）\n");
    printf("//\n");
    printf("// EnumMap — token 枚举标注 ('u32@Name' / '<>ptr@Name') 的值域表：全局\n");
    printf("// interface 声明合并（详见 lib/ffi/ctype.ts），用户可在自己的 .d.ts 里直接扩展。\n");
    printf("// 本文件是 module，故预填必须包在 declare global 内才对全局生效。\n");
    printf("declare global {\n");
    printf("    interface EnumMap {\n");
    /* 成员值直接写枚举名：本段就在 constants.ts 里，module 作用域内的 enum 在
       declare global 块里照常可见（无需 import('./constants') 自引）。 */
    for (i = 0; i < g_enum_count; i++)
        printf("        %s: %s\n", g_enum_names[i], g_enum_names[i]);

    /* 聚合消息枚举：msg 位（SendMessage/DefWindowProc）的值域是窗口消息 + 各控件消息
       的并集（WmMsg/TvMsg/LvMsg/...），单一枚举标不全 —— 按 *Msg 后缀自动收集。 */
    for (i = 0; i < g_enum_count; i++) {
        if (!has_msg_suffix(g_enum_names[i]))
            continue;
        if (first) {
            printf("\n");
            printf("        // 聚合消息枚举（生成器按 *Msg 后缀自动收集）：SendMessage/DefWindowProc 的\n");
            printf("        // msg 位值域 = 窗口消息 ∪ 各控件消息；标志位组合、通知码不在此域。\n");
            printf("        AnyMsg: ");
            first = 0;
        } else {
            printf(" | ");
        }
        printf("%s", g_enum_names[i]);
    }
    if (!first)
        printf("\n");

    printf("    }\n");
    printf("}\n");
}

