// ── Trusted CA bundle ──
//
// XP SP3 ships a root store frozen in 2008, so modern chains terminate
// in roots the OS does not know. Those roots are inlined here instead of
// being read from disk at handshake time: they travel inside the JS
// bundle and are pushed into wolfSSL's process-wide trust store as soon
// as this module is imported.
//
// The process-wide store has a fixed QW_CA_SLOTS (8) capacity; this
// bundle uses 7, leaving headroom for run-time registrations.
//
// Each anchor covers a different root hierarchy, and none is
// interchangeable: wolfSSL resolves a CA by AKID/SKID and does not walk
// every candidate, so a missing anchor fails the handshake with
// ASN_NO_SIGNER_E rather than falling back.
//
//   * GLOBALSIGN_R3 — cross-signed R3 (issued by R1, notAfter 2028-01-28,
//     SHA256 44:5E:EC:78:...:94:3D:4E:BB, RSA 2048). This is what the
//     post-2018 GlobalSign intermediates chain to: baidu.com, cdn.jsdelivr,
//     bilibili.com, jd.com.
//   * GLOBALSIGN_R1 — self-signed R1, the signer of the cross-signed R3.
//   * USERTRUST_ECC_CA — cross-signature parent of Sectigo Root E46
//     (github.com), EC P-384.
//   * DIGICERT_GLOBAL_G2 — cross-signature parent of Microsoft TLS RSA Root
//     G2 (bing.com), RSA 2048.
//   * GLOBALSIGN_R46, ISRG_X1, ISRG_X2 — the newer GlobalSign R46 and
//     Let's Encrypt hierarchies (taobao.com, qq.com).
//
// Known limitation (wolfSSL, not the bundle): GLOBALSIGN_R46 and ISRG_X1
// are RSA 4096, and this wolfSSL build compiles the SP bignum with
// SP_INT_BITS=3072 (the default when no FFDHE >= 4096 is enabled, see
// wolfcrypt/sp_int.h), so RSA_MAX_SIZE resolves to 3072 and wc_RsaVerify
// rejects a 4096-bit key with WC_KEY_SIZE_E (-234). asn.c flattens every
// crypto failure to ASN_SIG_CONFIRM_E, so those handshakes surface as
// -155. Raising SP_INT_BITS to 4096 in WOLFSSL_CMAKE_OPTS clears it; until
// then taobao.com, qq.com and bing.com fail.
//
// Import this module wherever the bundle needs to trust the public web.
// It is a no-op side effect: entries are registered at import time and
// picked up lazily by fetch()/WebSocket/the C module loader.

